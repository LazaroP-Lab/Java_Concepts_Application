    private void EqSigActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EqSigActionPerformed
        // TODO add your handling code here:
        secondnum = Double.parseDouble(Output.getText());
        if (operation.equals("+")) {
            result = firstnum + secondnum;
        } else if (operation.equals("-")) {
            result = firstnum - secondnum;
        } else if (operation.equals("*")) {
            result = firstnum * secondnum;
        } else if (operation.equals("/")) {
            result = firstnum / secondnum;
            if (secondnum == 0){
                Output.setText("Error");
                return;
            }
        }
        Output.setText(String.format("%.4f",result));
    }//GEN-LAST:event_EqSigActionPerformed

